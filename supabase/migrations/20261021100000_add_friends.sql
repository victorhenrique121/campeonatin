-- FC Arena: amizades entre perfis autenticados.

create table public.friends (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  friend_id uuid not null references public.profiles(id) on delete cascade,
  created_at timestamptz not null default now(),
  constraint friends_user_friend_unique unique (user_id, friend_id),
  constraint friends_not_self check (user_id <> friend_id)
);

create index friends_friend_id_idx on public.friends (friend_id);

alter table public.friends enable row level security;

revoke all on table public.friends from anon;
revoke all on table public.friends from authenticated;
grant select, insert, delete on table public.friends to authenticated;
grant usage, select on sequence public.friends_id_seq to authenticated;

create policy friends_select_own_or_friend
on public.friends
for select
to authenticated
using (
  user_id = (select auth.uid())
  or friend_id = (select auth.uid())
);

create policy friends_insert_own
on public.friends
for insert
to authenticated
with check (user_id = (select auth.uid()));

create policy friends_delete_own
on public.friends
for delete
to authenticated
using (user_id = (select auth.uid()));

-- A RLS de profiles permite leitura apenas do próprio perfil. Estas funções
-- devolvem somente os campos necessários à funcionalidade de amigos.
create or replace function public.find_friend_profile_by_username(p_username text)
returns table (
  id uuid,
  display_name text,
  username text,
  avatar_url text
)
language sql
stable
security definer
set search_path = ''
as $$
  select
    p.id,
    p.display_name,
    p.username,
    p.avatar_url
  from public.profiles as p
  where (select auth.uid()) is not null
    and p.username = lower(trim(p_username))
  limit 1;
$$;

create or replace function public.list_my_friends()
returns table (
  id uuid,
  display_name text,
  username text,
  avatar_url text
)
language sql
stable
security definer
set search_path = ''
as $$
  select distinct on (p.id)
    p.id,
    p.display_name,
    p.username,
    p.avatar_url
  from public.friends as f
  join public.profiles as p
    on p.id = case
      when f.user_id = (select auth.uid()) then f.friend_id
      else f.user_id
    end
  where (select auth.uid()) is not null
    and (
      f.user_id = (select auth.uid())
      or f.friend_id = (select auth.uid())
    )
  order by p.id, f.created_at;
$$;

revoke all on function public.find_friend_profile_by_username(text) from public, anon;
revoke all on function public.list_my_friends() from public, anon;
grant execute on function public.find_friend_profile_by_username(text) to authenticated;
grant execute on function public.list_my_friends() to authenticated;
