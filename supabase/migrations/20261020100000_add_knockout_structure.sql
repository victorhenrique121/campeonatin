-- Estrutura persistente para grupos, posições da chave e avanços automáticos.
alter table public.fixtures
  add column if not exists group_name text,
  add column if not exists bracket_position integer;

create index if not exists fixtures_championship_group_idx
  on public.fixtures (championship_id, group_name, round_number);

create index if not exists fixtures_championship_bracket_idx
  on public.fixtures (championship_id, round_number, bracket_position);

create unique index if not exists fixtures_championship_round_position_unique_idx
  on public.fixtures (championship_id, round_number, bracket_position)
  where bracket_position is not null;

create table if not exists public.knockout_byes (
  id bigint generated by default as identity primary key,
  championship_id bigint not null references public.championships(id) on delete cascade,
  round_number integer not null check (round_number > 0),
  player_id bigint not null references public.players(id) on delete restrict,
  position integer not null check (position > 0),
  unique (championship_id, round_number, position),
  unique (championship_id, round_number, player_id)
);

create index if not exists knockout_byes_championship_round_idx
  on public.knockout_byes (championship_id, round_number, position);

alter table public.knockout_byes enable row level security;

revoke all on table public.knockout_byes from anon;
grant select, insert, update, delete on table public.knockout_byes to authenticated;
revoke all on sequence public.knockout_byes_id_seq from anon;
grant usage, select on sequence public.knockout_byes_id_seq to authenticated;

drop policy if exists knockout_byes_select on public.knockout_byes;
drop policy if exists knockout_byes_insert on public.knockout_byes;
drop policy if exists knockout_byes_update on public.knockout_byes;
drop policy if exists knockout_byes_delete on public.knockout_byes;

create policy knockout_byes_select
on public.knockout_byes
for select to authenticated
using (
  exists (
    select 1
    from public.championships c
    where c.id = championship_id
      and (
        c.room_id is null
        or public.current_user_role() = 'admin'
        or (select public.is_room_member(c.room_id))
      )
  )
);

create policy knockout_byes_insert
on public.knockout_byes
for insert to authenticated
with check (
  exists (
    select 1
    from public.championships c
    where c.id = championship_id
      and (
        public.current_user_role() = 'admin'
        or public.room_member_role(c.room_id) in ('owner', 'admin')
      )
  )
);

create policy knockout_byes_update
on public.knockout_byes
for update to authenticated
using (
  exists (
    select 1
    from public.championships c
    where c.id = championship_id
      and (
        public.current_user_role() = 'admin'
        or public.room_member_role(c.room_id) in ('owner', 'admin')
      )
  )
)
with check (
  exists (
    select 1
    from public.championships c
    where c.id = championship_id
      and (
        public.current_user_role() = 'admin'
        or public.room_member_role(c.room_id) in ('owner', 'admin')
      )
  )
);

create policy knockout_byes_delete
on public.knockout_byes
for delete to authenticated
using (
  exists (
    select 1
    from public.championships c
    where c.id = championship_id
      and (
        public.current_user_role() = 'admin'
        or public.room_member_role(c.room_id) in ('owner', 'admin')
      )
  )
);
