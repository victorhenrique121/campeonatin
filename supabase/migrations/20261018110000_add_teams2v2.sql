create table public.teams2v2 (
  id bigint generated by default as identity primary key,
  room_id uuid references public.rooms(id) on delete cascade,
  player1_id bigint not null references public.players(id) on delete cascade,
  player2_id bigint not null references public.players(id) on delete cascade,
  name text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (player1_id < player2_id)
);

create unique index teams2v2_room_players_unique
  on public.teams2v2 (coalesce(room_id, '00000000-0000-0000-0000-000000000000'::uuid), player1_id, player2_id);

create trigger teams2v2_set_updated_at
  before update on public.teams2v2
  for each row execute function public.set_updated_at();

-- Limitação conhecida: mudar a sala de um jogador depois não valida as duplas;
-- resolver nas Fases 2/3.
create function public.validate_teams2v2_players()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not exists (
    select 1 from public.players p
    where p.id = new.player1_id and p.room_id is not distinct from new.room_id
  ) or not exists (
    select 1 from public.players p
    where p.id = new.player2_id and p.room_id is not distinct from new.room_id
  ) then
    raise exception 'Os jogadores devem pertencer à mesma sala.';
  end if;
  return new;
end;
$$;

revoke all on function public.validate_teams2v2_players() from public, anon;

create trigger teams2v2_validate_players
  before insert or update on public.teams2v2
  for each row execute function public.validate_teams2v2_players();

alter table public.teams2v2 enable row level security;

create policy teams2v2_select on public.teams2v2
  for select to authenticated
  using (room_id is null or public.current_user_role() = 'admin' or public.is_room_member(room_id));

create policy teams2v2_insert on public.teams2v2
  for insert to authenticated
  with check (public.current_user_role() = 'admin' or public.room_member_role(room_id) in ('owner', 'admin'));

create policy teams2v2_update on public.teams2v2
  for update to authenticated
  using (public.current_user_role() = 'admin' or public.room_member_role(room_id) in ('owner', 'admin'))
  with check (public.current_user_role() = 'admin' or public.room_member_role(room_id) in ('owner', 'admin'));

create policy teams2v2_delete on public.teams2v2
  for delete to authenticated
  using (public.current_user_role() = 'admin' or public.room_member_role(room_id) in ('owner', 'admin'));
