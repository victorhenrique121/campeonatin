-- FC Arena: notificações privadas entre usuários autenticados.

create table public.notifications (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  sender_id uuid not null references public.profiles(id) on delete cascade,
  type text not null,
  payload jsonb not null default '{}'::jsonb,
  read_at timestamptz,
  created_at timestamptz not null default now()
);

create index notifications_user_unread_created_idx
  on public.notifications (user_id, created_at desc)
  where read_at is null;

alter table public.notifications enable row level security;

revoke all on table public.notifications from anon;
revoke all on table public.notifications from authenticated;
revoke all on sequence public.notifications_id_seq from anon;
revoke all on sequence public.notifications_id_seq from authenticated;

create or replace function public.send_room_invite(
  p_recipient_id uuid,
  p_room_id uuid
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_sender_id uuid := auth.uid();
begin
  if v_sender_id is null then
    raise exception 'Sua sessão expirou. Entre novamente para continuar.';
  end if;

  if v_sender_id = p_recipient_id then
    raise exception 'Você não pode convidar a si mesmo.';
  end if;

  if not exists (
    select 1
    from public.room_members as rm
    join public.rooms as r on r.id = rm.room_id
    where rm.room_id = p_room_id
      and rm.user_id = v_sender_id
      and rm.role in ('owner', 'admin')
      and r.deleted_at is null
  ) then
    raise exception 'Você não tem permissão para convidar pessoas para esta sala.';
  end if;

  if not exists (
    select 1
    from public.friends as f
    where f.user_id = v_sender_id
      and f.friend_id = p_recipient_id
  ) then
    raise exception 'Você só pode convidar pessoas da sua lista de amigos.';
  end if;

  if exists (
    select 1
    from public.blocked_users as b
    where (b.user_id = v_sender_id and b.blocked_id = p_recipient_id)
       or (b.user_id = p_recipient_id and b.blocked_id = v_sender_id)
  ) then
    raise exception 'Não é possível enviar convite para este usuário.';
  end if;

  if exists (
    select 1
    from public.room_members as rm
    where rm.room_id = p_room_id
      and rm.user_id = p_recipient_id
  ) then
    raise exception 'Este amigo já participa da sala.';
  end if;

  insert into public.notifications (user_id, sender_id, type, payload)
  values (
    p_recipient_id,
    v_sender_id,
    'room_invite',
    jsonb_build_object('roomId', p_room_id)
  );
end;
$$;

create or replace function public.list_unread_notifications()
returns table (
  id bigint,
  sender_id uuid,
  type text,
  payload jsonb,
  created_at timestamptz
)
language sql
stable
security definer
set search_path = ''
as $$
  select
    n.id,
    n.sender_id,
    n.type,
    n.payload,
    n.created_at
  from public.notifications as n
  where n.user_id = (select auth.uid())
    and n.read_at is null
  order by n.created_at desc;
$$;

create or replace function public.mark_notification_read(p_notification_id bigint)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  update public.notifications
  set read_at = coalesce(read_at, now())
  where id = p_notification_id
    and user_id = (select auth.uid());
end;
$$;

revoke all on function public.send_room_invite(uuid, uuid) from public, anon;
revoke all on function public.list_unread_notifications() from public, anon;
revoke all on function public.mark_notification_read(bigint) from public, anon;
grant execute on function public.send_room_invite(uuid, uuid) to authenticated;
grant execute on function public.list_unread_notifications() to authenticated;
grant execute on function public.mark_notification_read(bigint) to authenticated;
