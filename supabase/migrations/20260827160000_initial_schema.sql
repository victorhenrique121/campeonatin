-- Matches: everyone authenticated can read. Admin can do everything.
-- A player may INSERT a result only if the match belongs to that player.
-- Once inserted, that player cannot UPDATE it: corrections belong to admins.
create policy matches_select_authenticated on public.matches
for select to authenticated using (true);

create policy matches_insert_admin_or_own_player on public.matches
for insert to authenticated
with check (
  public.current_user_role() = 'admin'
  or exists (
    select 1 from public.players p
    where p.user_id = auth.uid()
      and (p.id = player1_id or p.id = player2_id)
  )
);

create policy matches_update_admin on public.matches
for update to authenticated
using (public.current_user_role() = 'admin')
with check (public.current_user_role() = 'admin');

create policy matches_delete_admin on public.matches
for delete to authenticated
using (public.current_user_role() = 'admin');

