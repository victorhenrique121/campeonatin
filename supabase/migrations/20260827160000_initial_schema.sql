-- Profiles: authenticated users can read their own profile. Admins can read all.
create policy profiles_select_own_or_admin on public.profiles
for select to authenticated
using (id = auth.uid() or public.current_user_role() = 'admin');

create policy profiles_update_own_or_admin on public.profiles
for update to authenticated
using (id = auth.uid() or public.current_user_role() = 'admin')
with check (id = auth.uid() or public.current_user_role() = 'admin');

-- Players: everyone authenticated can read. A player can update only their
-- own linked player row; admins can manage all player rows.
create policy players_select_authenticated on public.players
for select to authenticated using (true);

create policy players_insert_admin on public.players
for insert to authenticated
with check (public.current_user_role() = 'admin');

create policy players_update_own_or_admin on public.players
for update to authenticated
using (public.current_user_role() = 'admin' or user_id = auth.uid())
with check (public.current_user_role() = 'admin' or user_id = auth.uid());

create policy players_delete_admin on public.players
for delete to authenticated
using (public.current_user_role() = 'admin');

-- Teams are read-only for non-admin users.
create policy teams_select_authenticated on public.teams
for select to authenticated using (true);

create policy teams_insert_admin on public.teams
