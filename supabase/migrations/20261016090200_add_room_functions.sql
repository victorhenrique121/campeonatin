-- Contrato: join_room(codigo) devolve o UUID da sala em caso de sucesso ou NULL
-- em caso de falha; não devolve a linha da sala e não lança exceção.

create table public.room_join_attempts (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  attempted_at timestamptz not null default now()
);
create index room_join_attempts_user_time_idx on public.room_join_attempts (user_id, attempted_at desc);
alter table public.room_join_attempts enable row level security;
revoke all on public.room_join_attempts from anon, authenticated;

create or replace function public.room_entry_code()
returns text language plpgsql volatile security definer set search_path = '' as $$
declare alphabet constant text := 'ABCDEFGHJKMNPQRSTUVWXYZ23456789'; result text := ''; b integer;
begin
  while char_length(result) < 8 loop
    b := get_byte(extensions.gen_random_bytes(1), 0);
    if b < 248 then
      result := result || substr(alphabet, (b % 31) + 1, 1);
    end if;
  end loop;
  return result;
end; $$;

create or replace function public.is_room_member(p_room_id uuid)
returns boolean language sql stable security definer set search_path = '' as $$
  select auth.uid() is not null and exists (
    select 1 from public.room_members rm join public.rooms r on r.id = rm.room_id
    where rm.room_id = p_room_id and rm.user_id = auth.uid() and r.deleted_at is null
  );
$$;

create or replace function public.room_member_role(p_room_id uuid)
returns public.room_member_role language sql stable security definer set search_path = '' as $$
  select rm.role from public.room_members rm join public.rooms r on r.id = rm.room_id
  where rm.room_id = p_room_id and rm.user_id = auth.uid() and r.deleted_at is null;
$$;

create or replace function public.room_member_profiles(p_room_id uuid)
returns table(display_name text, username text, avatar_url text)
language sql stable security definer set search_path = '' as $$
  select p.display_name, p.username, p.avatar_url
  from public.room_members rm join public.profiles p on p.id = rm.user_id
  where public.is_room_member(p_room_id) and rm.room_id = p_room_id;
$$;

create or replace function public.create_room(p_name text)
returns public.rooms language plpgsql security definer set search_path = '' as $$
declare v_user uuid := auth.uid(); v_code text; v_room public.rooms; v_try integer;
begin
  if v_user is null or char_length(trim(coalesce(p_name, ''))) not between 1 and 80 then raise exception 'Nome da sala inválido.'; end if;
  for v_try in 1..10 loop
    v_code := public.room_entry_code();
    begin
      insert into public.rooms(name, entry_code, created_by) values (trim(p_name), v_code, v_user) returning * into v_room;
      insert into public.room_members(room_id, user_id, role) values (v_room.id, v_user, 'owner');
      return v_room;
    exception when unique_violation then null;
    end;
  end loop;
  raise exception 'Não foi possível criar a sala. Tente novamente.';
end; $$;

drop function if exists public.join_room(text);
create or replace function public.join_room(p_code text)
returns uuid language plpgsql security definer set search_path = '' as $$
declare v_user uuid := auth.uid(); v_code text := upper(trim(coalesce(p_code, ''))); v_room_id uuid; v_attempts integer;
begin
  if v_user is null then return null; end if;
  delete from public.room_join_attempts where attempted_at < now() - interval '1 day';
  insert into public.room_join_attempts(user_id) values (v_user);
  select count(*) into v_attempts from public.room_join_attempts where user_id = v_user and attempted_at >= now() - interval '15 minutes';
  if v_attempts > 5 then return null; end if;
  select id into v_room_id from public.rooms where entry_code = v_code and deleted_at is null;
  if v_room_id is null then return null; end if;
  insert into public.room_members(room_id, user_id) values (v_room_id, v_user) on conflict (room_id, user_id) do nothing;
  return v_room_id;
end; $$;

create or replace function public.regenerate_room_code(p_room_id uuid)
returns text language plpgsql security definer set search_path = '' as $$
declare v_code text; v_try integer;
begin
  if public.room_member_role(p_room_id) not in ('owner', 'admin') then raise exception 'Sem permissão para regenerar o código.'; end if;
  for v_try in 1..10 loop
    v_code := public.room_entry_code();
    begin update public.rooms set entry_code = v_code where id = p_room_id and deleted_at is null; return v_code;
    exception when unique_violation then null;
    end;
  end loop;
  raise exception 'Não foi possível regenerar o código. Tente novamente.';
end; $$;

revoke all on function public.room_entry_code() from public, anon;
revoke all on function public.is_room_member(uuid) from public, anon;
revoke all on function public.room_member_role(uuid) from public, anon;
revoke all on function public.room_member_profiles(uuid) from public, anon;
revoke all on function public.create_room(text) from public, anon;
revoke all on function public.join_room(text) from public, anon;
revoke all on function public.regenerate_room_code(uuid) from public, anon;
grant execute on function public.is_room_member(uuid), public.room_member_role(uuid), public.room_member_profiles(uuid), public.create_room(text), public.join_room(text), public.regenerate_room_code(uuid) to authenticated;

create policy rooms_select_member on public.rooms for select to authenticated using ((select public.is_room_member(id)));
create policy room_members_select_member on public.room_members for select to authenticated using ((select public.is_room_member(room_id)));
