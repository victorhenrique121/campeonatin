-- FC Arena: bloqueios entre perfis autenticados.

create table public.blocked_users (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  blocked_id uuid not null references public.profiles(id) on delete cascade,
  created_at timestamptz not null default now(),
  constraint blocked_users_user_blocked_unique unique (user_id, blocked_id),
  constraint blocked_users_not_self check (user_id <> blocked_id)
);

create index blocked_users_blocked_id_idx on public.blocked_users (blocked_id);

alter table public.blocked_users enable row level security;

revoke all on table public.blocked_users from anon;
revoke all on table public.blocked_users from authenticated;
grant select, insert, delete on table public.blocked_users to authenticated;
grant usage, select on sequence public.blocked_users_id_seq to authenticated;

create policy blocked_users_select_own
on public.blocked_users
for select
to authenticated
using (user_id = (select auth.uid()));

create policy blocked_users_insert_own
on public.blocked_users
for insert
to authenticated
with check (user_id = (select auth.uid()));

create policy blocked_users_delete_own
on public.blocked_users
for delete
to authenticated
using (user_id = (select auth.uid()));

-- Substitui as RPCs de amigos para não revelar nem listar usuários bloqueados.
create or replace function public.find_friend_profile_by_username(p_username text)
returns table (
  id uuid,
  display_name text,
  username text,
  avatar_url text
)
language sql
stable
security definer
set search_path = ''
as $$
  select
    p.id,
    p.display_name,
    p.username,
    p.avatar_url
  from public.profiles as p
  where (select auth.uid()) is not null
    and p.username = lower(trim(p_username))
    and not exists (
      select 1
      from public.blocked_users as b
      where (b.user_id = (select auth.uid()) and b.blocked_id = p.id)
         or (b.user_id = p.id and b.blocked_id = (select auth.uid()))
    )
  limit 1;
$$;

create or replace function public.list_my_friends()
returns table (
  id uuid,
  display_name text,
  username text,
  avatar_url text
)
language sql
stable
security definer
set search_path = ''
as $$
  select
    p.id,
    p.display_name,
    p.username,
    p.avatar_url
  from public.friends as f
  join public.profiles as p on p.id = f.friend_id
  where f.user_id = (select auth.uid())
    and not exists (
      select 1
      from public.blocked_users as b
      where (b.user_id = (select auth.uid()) and b.blocked_id = f.friend_id)
         or (b.user_id = f.friend_id and b.blocked_id = (select auth.uid()))
    )
  order by lower(p.display_name), p.id;
$$;

revoke all on function public.find_friend_profile_by_username(text) from public, anon;
revoke all on function public.list_my_friends() from public, anon;
grant execute on function public.find_friend_profile_by_username(text) to authenticated;
grant execute on function public.list_my_friends() to authenticated;
